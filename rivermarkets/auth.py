"""Ed25519 request signing for the River Markets API.

Hand-written — not generated by Fern. Do not delete on regen.
See https://docs.rivermarkets.com/api-reference/authentication for the
canonical-string format and header contract.

Every signed request also carries ``X-River-Org-Id``: API-key traffic is rate
limited per organization on that header, and a request without it (or with the
wrong org) is refused with 403. The signer learns the org id once from
``GET /v1/rate-limit`` (the one route that does not require the header) and
caches it for the life of the client; pass ``org_id`` to skip that round trip.
"""

import base64
import hashlib
import time
import typing
from urllib.parse import parse_qsl, quote, urlencode

import httpx
from nacl.signing import SigningKey

ORG_HEADER = "X-River-Org-Id"
RATE_LIMIT_PATH = "/v1/rate-limit"


class RiverMarketsSigner(httpx.Auth):
    requires_request_body = True
    requires_response_body = True

    def __init__(self, key_id: str, private_key: str, org_id: typing.Optional[str] = None):
        self._key_id = key_id
        self._signing_key = SigningKey(base64.b64decode(private_key))
        self._org_id = org_id

    @property
    def org_id(self) -> typing.Optional[str]:
        return self._org_id

    def auth_flow(
        self, request: httpx.Request
    ) -> typing.Generator[httpx.Request, httpx.Response, None]:
        if self._org_id is None and request.url.path != RATE_LIMIT_PATH:
            bootstrap = httpx.Request("GET", request.url.copy_with(path=RATE_LIMIT_PATH, query=b""))
            self._sign(bootstrap)
            response = yield bootstrap
            if response.status_code == 200:
                self._org_id = str(response.json()["org_id"])

        self._sign(request)
        response = yield request

        # The key moved to another org since we cached it: the server names the
        # right org in the 403 body. Re-sign (fresh timestamp) and retry once.
        if response.status_code == 403:
            corrected = self._org_from_mismatch(response)
            if corrected is not None and corrected != self._org_id:
                self._org_id = corrected
                self._sign(request)
                yield request

    @staticmethod
    def _org_from_mismatch(response: httpx.Response) -> typing.Optional[str]:
        try:
            detail = response.json().get("detail")
        except ValueError:
            return None
        if isinstance(detail, dict) and detail.get("error") in ("org_header_mismatch", "org_header_required"):
            org_id = detail.get("org_id")
            return str(org_id) if org_id else None
        return None

    def _sign(self, request: httpx.Request) -> None:
        url = request.url
        sorted_query = urlencode(
            sorted(parse_qsl(url.query.decode("ascii"), keep_blank_values=True)),
            quote_via=quote,
        )
        body = request.content or b""
        ts = str(int(time.time() * 1000))
        canonical = "\n".join(
            [
                request.method.upper(),
                url.path,
                sorted_query,
                ts,
                hashlib.sha256(body).hexdigest(),
            ]
        ).encode()
        signature = self._signing_key.sign(canonical).signature
        request.headers["X-River-Key-Id"] = self._key_id
        request.headers["X-River-Timestamp"] = ts
        request.headers["X-River-Signature"] = base64.b64encode(signature).decode()
        if self._org_id is not None:
            request.headers[ORG_HEADER] = self._org_id
        else:
            request.headers.pop(ORG_HEADER, None)
